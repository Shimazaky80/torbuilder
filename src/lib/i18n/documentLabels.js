export const statusLabelKey = (status) => {
  const normalised = String(status ?? '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z]+/g, '_')
    .replace(/^_+|_+$/g, '');
  const resolved = STATUS_ALIASES[normalised] || 'quotation';
  return STATUS_LABEL_KEYS[resolved];
};
