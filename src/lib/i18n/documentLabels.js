/* Document labels, per language.

   Only exported documents follow these; the app chrome stays English by the
   operator's decision. A key that no dictionary carries falls back to English,
   and a key no dictionary defines at all prints its own name - visible enough
   that a missing label is caught in a proof print rather than silently
   swallowed.

   The English column is the specification: every phrase here is copied from the
   template string it replaces, so an English export comes out byte-identical to
   the document the builder prints today.

   A value is either a string, or an object of plural forms keyed by the
   categories Intl.PluralRules answers with for that language's locale - which
   is why "{n} travellers" cannot be one string: French counts 0 and 1 together,
   German and Spanish do not. */

